import { test, expect } from '@playwright/test';
test.use({ hasTouch: true, isMobile: true, viewport: { width: 412, height: 900 } });
test('plural clone on a touch screen: hint, pick by tap, stale pick ignored', async ({ page }) => {
  const xml = `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <plurals name="files">\n        <item quantity="one">%d file</item>\n        <item quantity="other">%d files</item>\n    </plurals>\n</resources>`;
  await page.goto('/');
  await page.click('#header-right-drawer-btn');
  await page.click('#drawer-import-btn');
  await page.fill('#import-project-name', 'T');
  await page.getByRole('button', { name: /لصق نص XML|Paste XML/ }).click();
  await page.locator('textarea').last().fill(xml);
  await page.locator('select').first().selectOption('ar');
  await page.getByRole('button', { name: /بدء الترجمة|Start Translating/ }).click();
  const fields = page.locator('textarea:visible');
  if (process.env.SHOT_DIR) await page.screenshot({ path: `${process.env.SHOT_DIR}/plural-source-forms-mobile.png` });
  await page.locator('#weblate-clone-source-one-btn').tap();
  await expect(page.getByTestId('plural-pick-hint')).toBeVisible();
  if (process.env.SHOT_DIR) await page.screenshot({ path: `${process.env.SHOT_DIR}/plural-pick-mobile.png` });
  await fields.nth(1).tap();
  await expect(fields.nth(1)).toHaveValue('%d file');
  await expect(fields.nth(0)).toHaveValue('');
  await expect(page.getByTestId('plural-pick-hint')).toHaveCount(0);
  await fields.nth(2).tap();
  await page.locator('#weblate-clone-source-other-btn').tap();
  await expect(fields.nth(2)).toHaveValue('%d files');
  await page.locator('[data-src-text]').tap();
  await page.locator('#weblate-clone-source-one-btn').tap();
  await expect(page.getByTestId('plural-pick-hint')).toBeVisible();
});

test('string-array on a touch screen: item tools and delete pick by tap', async ({ page }) => {
  const xml = `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <string-array name="choices">\n        <item>First choice</item>\n        <item>Second choice</item>\n        <item>Third choice</item>\n    </string-array>\n</resources>`;
  await page.goto('/');
  await page.click('#header-right-drawer-btn');
  await page.click('#drawer-import-btn');
  await page.fill('#import-project-name', 'T');
  await page.getByRole('button', { name: /لصق نص XML|Paste XML/ }).click();
  await page.locator('textarea').last().fill(xml);
  await page.locator('select').first().selectOption('hi');
  await page.getByRole('button', { name: /بدء الترجمة|Start Translating/ }).click();
  const fields = page.locator('textarea:visible');
  await page.getByTestId('array-clone-0').tap();
  await page.getByTestId('array-clone-2').tap();
  await expect(fields.nth(0)).toHaveValue('First choice');
  if (process.env.SHOT_DIR) await page.screenshot({ path: `${process.env.SHOT_DIR}/array-mobile.png` });
  await page.locator('#weblate-quick-delete-btn').tap();
  await expect(page.getByTestId('plural-pick-hint')).toBeVisible();
  if (process.env.SHOT_DIR) await page.screenshot({ path: `${process.env.SHOT_DIR}/array-mobile-delete.png` });
  await fields.nth(2).tap();
  await expect(fields.nth(2)).toHaveValue('');
  await expect(fields.nth(0)).toHaveValue('First choice');
  await expect(page.getByTestId('plural-pick-hint')).toHaveCount(0);

  // "Delete all" by tap clears every item (nothing focused, so delete shows the hint)
  await page.locator('[data-key-name]').tap();
  await page.locator('#weblate-quick-delete-btn').tap();
  await expect(page.getByTestId('plural-delete-all')).toBeVisible();
  if (process.env.SHOT_DIR) await page.screenshot({ path: `${process.env.SHOT_DIR}/delete-all-mobile.png` });
  await page.getByTestId('plural-delete-all').tap();
  for (let i = 0; i < 3; i++) await expect(fields.nth(i)).toHaveValue('');
  await expect(page.getByTestId('plural-pick-hint')).toHaveCount(0);
});
